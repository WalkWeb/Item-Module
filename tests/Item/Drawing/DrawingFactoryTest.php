    /**
     * @dataProvider successDataProvider
     * @param array $data
     * @param int $expectedPrice
     * @param DamageTypeInterface|null $expectedDamageType
     * @throws ItemException
     */
    public function testDrawingFactoryCreateSuccess(
        array $data,
        int $expectedPrice,
        ?DamageTypeInterface $expectedDamageType
    ): void
    {
        $drawing = DrawingFactory::create($data);

        self::assertEquals($data['id'], $drawing->getId());
        self::assertEquals($data['name'], $drawing->getName());
        self::assertEquals($data['icon'], $drawing->getIcon());
        self::assertEquals($expectedPrice, $drawing->getPrice());
        self::assertEquals($data['weight'], $drawing->getWeight());
        self::assertEquals($data['min_level'], $drawing->getMinLevel());
        self::assertEquals($data['strength'], $drawing->getStrength());
        self::assertEquals($data['dexterity'], $drawing->getDexterity());
        self::assertEquals($data['intelligence'], $drawing->getIntelligence());
        self::assertEquals($data['affix_exception'], $drawing->getAffixException());
        self::assertEquals($data['type_id'], $drawing->getType()->getId());
        self::assertEquals($expectedDamageType, $drawing->getDamageType());

        if (array_key_exists('equip_type_id', $data) && $data['equip_type_id'] !== null) {
            self::assertEquals($data['equip_type_id'], $drawing->getEquipType()->getId());
        } else {
            self::assertNull($drawing->getEquipType());
        }

        if (array_key_exists('section_type_id', $data) && $data['section_type_id'] !== null) {
            self::assertEquals($data['section_type_id'], $drawing->getSectionType()->getId());
        } else {
            self::assertNull($drawing->getSectionType());
        }

        if (array_key_exists('weapon_type_id', $data) && $data['weapon_type_id'] !== null) {
            self::assertEquals($data['weapon_type_id'], $drawing->getWeaponType()->getId());
        } else {
            self::assertNull($drawing->getWeaponType());
        }

        if (array_key_exists('armor_type_id', $data) && $data['armor_type_id'] !== null) {
            self::assertEquals($data['armor_type_id'], $drawing->getArmorType()->getId());
        } else {
            self::assertNull($drawing->getArmorType());
        }

        if (array_key_exists('potion_type_id', $data) && $data['potion_type_id'] !== null) {
            self::assertEquals($data['potion_type_id'], $drawing->getPotionType()->getId());
        } else {
            self::assertNull($drawing->getPotionType());
        }

        if (array_key_exists('material_type_id', $data) && $data['material_type_id'] !== null) {
            self::assertEquals($data['material_type_id'], $drawing->getMaterialType()->getId());
        } else {
            self::assertNull($drawing->getMaterialType());
        }

        if (array_key_exists('gender_type_id', $data) && $data['gender_type_id'] !== null) {
            self::assertEquals($data['gender_type_id'], $drawing->getGenderType()->getId());
        } else {
            self::assertNull($drawing->getGenderType());
        }

        if (array_key_exists('magic_type_id', $data) && $data['magic_type_id'] !== null) {
            self::assertEquals($data['magic_type_id'], $drawing->getMagicType()->getId());
        } else {
            self::assertNull($drawing->getMagicType());
        }

        self::assertEquals(
            $data['equip_type_id'] && $data['equip_type_id'] === EquipTypeInterface::TWO_HAND,
            $drawing->isTwoHand()
        );

        self::assertSameSize($data['stats'], $drawing->getStats());

        $i = 0;
        foreach ($drawing->getStats() as $stat) {
            self::assertEquals($data['stats'][$i]['name'], $stat->getName());
            self::assertEquals($data['stats'][$i]['value'], $stat->getValue());
            self::assertEquals($data['stats'][$i]['quality'], $stat->isQuality());
            self::assertEquals($data['stats'][$i]['prefix'], $stat->getPrefix());
            self::assertEquals($data['stats'][$i]['suffix'], $stat->getSuffix());
            $i++;
        }
    }

    /**
     * @dataProvider failDataProvider
     * @param array $data
     * @param string $error
     */
    public function testDrawingFactoryCreateFail(array $data, string $error): void
    {
        $this->expectException(ItemException::class);
        $this->expectExceptionMessage($error);
        DrawingFactory::create($data);
    }


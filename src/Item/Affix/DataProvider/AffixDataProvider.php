    /**
     * @return AffixCollection
     * @throws ItemException
     */
    public static function getAll(): AffixCollection
    {
        return AffixCollectionFactory::create(self::$affixes);
    }

    /**
     * @param DrawingInterface $drawing
     * @param MagicTypeInterface $magicType
     * @param MagicQualityInterface $magicQuality
     * @param int $itemLevel
     * @return AffixCollection
     * @throws Exception
     */
    public static function get(
        DrawingInterface $drawing,
        MagicTypeInterface $magicType,
        MagicQualityInterface $magicQuality,
        int $itemLevel
    ): AffixCollection
    {
        $availableAffixes = [];
        $selectedAffixes = [];
        $count = 0;
        $maxCount = $magicQuality->getId();
        $availableTypes = self::$types[$magicType->getId()];

        // select available affixes
        foreach (self::$affixes as $affix) {
            if (
                $affix['min_level'] <= $itemLevel
                && in_array($affix['type_id'], $availableTypes, true)
                && !in_array($affix['type_id'], $drawing->getAffixException(), true)
            ) {
                $availableAffixes[] = $affix;
            }
        }

        // select random affixes from available
        while ($count < $maxCount) {
            $affix = $availableAffixes[array_rand($availableAffixes, 1)];

            if (!array_key_exists($affix['type_id'], $selectedAffixes) && random_int(1, 100) <= $affix['rarity']) {
                $selectedAffixes[$affix['type_id']] = $affix;
                $count++;
            }
        }

        return AffixCollectionFactory::create($selectedAffixes);
    }
